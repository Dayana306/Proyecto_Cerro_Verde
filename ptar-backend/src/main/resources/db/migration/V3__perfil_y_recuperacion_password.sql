-- Nuevas funciones: foto de perfil y restablecimiento seguro de contraseña.
-- V1/V2 se conservan inmutables para no afectar entornos que ya las aplicaron.
ALTER TABLE usuario ADD COLUMN foto_perfil TEXT NULL;

CREATE TABLE password_reset_token (
  id_token BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INT NOT NULL,
  token_hash CHAR(64) NOT NULL,
  fecha_expiracion TIMESTAMP NOT NULL,
  usado BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_password_reset_token_hash UNIQUE (token_hash),
  CONSTRAINT fk_password_reset_token_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario)
);

-- Índices secundarios PostgreSQL
CREATE INDEX idx_password_reset_usuario_estado ON password_reset_token (id_usuario, usado);
CREATE INDEX idx_password_reset_expiracion ON password_reset_token (fecha_expiracion);
