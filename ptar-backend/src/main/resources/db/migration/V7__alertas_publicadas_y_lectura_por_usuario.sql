-- Alertas publicadas manualmente por administración, con seguimiento de lectura independiente.
CREATE TABLE alerta_publicada (
    id_alerta_publicada INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(120) NOT NULL,
    descripcion VARCHAR(2000) NOT NULL,
    nivel VARCHAR(10) NOT NULL DEFAULT 'MEDIA',
    area VARCHAR(120),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario_creador INTEGER NOT NULL,
    CONSTRAINT ck_alerta_publicada_nivel CHECK (nivel IN ('MEDIA', 'ALTA')),
    CONSTRAINT fk_alerta_publicada_creador FOREIGN KEY (id_usuario_creador) REFERENCES usuario(id_usuario)
);

CREATE INDEX idx_alerta_publicada_fecha ON alerta_publicada(fecha_creacion DESC);

CREATE TABLE alerta_publicada_lectura (
    id_lectura INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_lectura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_alerta_publicada INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,
    CONSTRAINT uq_alerta_publicada_usuario UNIQUE (id_alerta_publicada, id_usuario),
    CONSTRAINT fk_alerta_publicada_lectura_alerta FOREIGN KEY (id_alerta_publicada)
        REFERENCES alerta_publicada(id_alerta_publicada) ON DELETE CASCADE,
    CONSTRAINT fk_alerta_publicada_lectura_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
);

CREATE INDEX idx_alerta_publicada_lectura_usuario ON alerta_publicada_lectura(id_usuario);
