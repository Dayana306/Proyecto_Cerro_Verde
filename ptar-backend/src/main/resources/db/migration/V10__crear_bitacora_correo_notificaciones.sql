-- Bitácora adicional para los correos enviados desde el nuevo módulo Notificaciones.
-- Solo crea una tabla nueva; no modifica ni elimina los datos ya existentes.
CREATE TABLE IF NOT EXISTS correo_notificacion (
    id_correo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatarios TEXT NOT NULL,
    asunto VARCHAR(180) NOT NULL,
    mensaje TEXT NOT NULL,
    es_html BOOLEAN NOT NULL DEFAULT FALSE,
    nombres_adjuntos TEXT,
    estado VARCHAR(16) NOT NULL DEFAULT 'PENDIENTE',
    fecha_envio TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    error_resumen VARCHAR(500),
    id_usuario INTEGER,
    CONSTRAINT ck_correo_notificacion_estado CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'ERROR')),
    CONSTRAINT fk_correo_notificacion_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_correo_notificacion_fecha
    ON correo_notificacion (fecha_envio DESC);
CREATE INDEX IF NOT EXISTS idx_correo_notificacion_estado
    ON correo_notificacion (estado);
